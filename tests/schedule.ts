import assert from 'node:assert/strict';
import {progressFor,periodsInMonth,monthBefore,isActiveOn,wasActiveBetween} from '../lib/schedule.ts';
import type {RecordItem} from '../lib/domain.ts';
const row=(kind:string,key:string,data:any):RecordItem=>({owner:'test',kind,key,data,version:1,updated:''});
const plan=(versions:any[])=>row('habit_plan','exercise',{versions});
const checks=(days:string[])=>days.map(d=>row('checks',d,{exercise:'done'}));
const rows=[plan([{from:'2026-08-01',period:'week',target:3,active:true}]),...checks(['2026-08-03','2026-08-05','2026-08-07','2026-08-08'])];
let p=progressFor(rows,'exercise','2026-08-05','2026-08-31');assert.equal(p.done,4);assert.equal(p.percent,100);assert.equal(p.extra,1);
p=progressFor(rows,'exercise','2026-08-12','2026-08-31');assert.equal(p.done,0);assert.equal(p.percent,0);assert.equal(p.open,false);
p=progressFor(rows,'exercise','2026-08-05','2026-08-06');assert.equal(p.done,2);assert.equal(p.open,true);
console.log('PASS Weekly targets count distinct days, cap at 100%, exclude future marks and do not carry surplus');
const changing=[plan([{from:'2026-08-01',period:'week',target:3,active:true},{from:'2026-08-12',period:'week',target:4,active:true}]),...checks(['2026-08-03','2026-08-05','2026-08-07'])];
assert.equal(progressFor(changing,'exercise','2026-08-03','2026-08-31').target,3);
assert.equal(progressFor(changing,'exercise','2026-08-12','2026-08-31').target,null);
assert.equal(progressFor(changing,'exercise','2026-08-18','2026-08-31').target,4);
assert.equal(progressFor(changing,'exercise','2026-07-01','2026-08-31').percent,null);
assert.equal(progressFor(rows,'exercise','2026-08-01','2026-08-31').partial,true);
console.log('PASS Unknown history, initial partial weeks and changed targets cannot become full-period failures');
assert.equal(monthBefore('2026-01'),'2025-12');
const monthly=[plan([{from:'2024-02-01',period:'month',target:2,active:true}]),...checks(['2024-02-01','2024-02-29'])];
assert.equal(progressFor(monthly,'exercise','2024-02-29','2024-03-01').end,'2024-02-29');
assert.equal(progressFor(monthly,'exercise','2024-02-29','2024-03-01').percent,100);
assert.equal(periodsInMonth(rows,'exercise','2026-08','2026-09-10').length,6);
const paused=[plan([{from:'2026-08-01',period:'week',target:3,active:true},{from:'2026-08-12',period:'week',target:3,active:false}])];
const habit=row('habit','exercise',{active:false});assert(isActiveOn(paused,habit,'2026-08-05'));assert(!isActiveOn(paused,habit,'2026-08-13'));
assert.equal(progressFor(paused,'exercise','2026-08-10','2026-08-31').target,null);
console.log('PASS Calendar boundaries, monthly targets and historic pauses');

assert(wasActiveBetween(paused,'exercise','2026-08-01','2026-08-31'));
assert(!wasActiveBetween(paused,'exercise','2026-09-01','2026-09-30'));
assert(!wasActiveBetween(paused,'exercise','2026-07-01','2026-07-31'));
